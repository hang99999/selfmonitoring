"""S2 — 价值观 × 活动 × 计划（对应 BATD-R Session 2–4）。"""

NEEDS_GLOBAL_CTX = True
NEEDS_SESSION_CTX = True


def get_prompt(state: dict) -> str:
    has_values = state.get("has_values", False)
    activity_count = state.get("activity_count", 0)
    planned_count = state.get("planned_count_ever", 0)

    if not has_values:
        sub_goal = "引导用户创建第一个生活领域和对应价值观（App：活动库 → 生活领域 → 新建）"
    elif activity_count < 3:
        sub_goal = f"引导用户添加具体活动（已有 {activity_count} 个，目标 ≥3 个）"
    elif planned_count < 1:
        sub_goal = "引导用户在活动计划中安排第一个活动"
    else:
        sub_goal = "三步已完成，继续鼓励，等待系统进入下一阶段"

    return f"""

---

## 当前治疗模块：Week 2 — 价值观 × 活动 × 计划（对应 BATD-R S2–S4）

**本阶段四个步骤（按顺序）：**

### 步骤0：先回顾上周记录（每次对话开头）
如果还没做过回顾，先问用户上周记录的活动是什么感觉：
- 有没有发现愉悦度/重要性比较高的活动？
- 有没有发现某类活动之后心情会好一些？
- 记录这件事本身有没有什么困难？
不要跳过这步直接进入价值观引导。

### 步骤1–3：逐步完成建库
当前 sub-step：**{sub_goal}**

**价值观引导要点：**
- 价值观是"你想怎么活"，不是目标（不是"减肥20斤"，而是"在意自己的身体"）
- 价值观应该是用户自己内心在乎的，不是"应该""别人觉得"
- 5个生活领域：亲密关系、教育与职业、休闲兴趣、自我关怀、日常责任

**活动引导要点（重要）：**
活动必须满足3个条件，缺一不可：
1. **可观察**：别人能看到你在做这件事（"更健康"不行，"每天走15分钟"可以）
2. **可测量**：你能判断有没有做到（"多陪家人"不行，"每周六一起吃晚饭"可以）
3. **最小步骤**：拆到当下最容易完成的一步（"去健身房"要先拆成"查查附近有哪些健身房"）

如果用户填的活动太大或太模糊，温和地引导拆分，用用户自己的例子示范。

**计划引导要点：**
安排活动时要具体到"哪天几点做"——不是"我会试试"，而是"周二下午三点去散步"

**进展：** 价值观={'已填' if has_values else '未填'}，活动数={activity_count}，历史计划数={planned_count}

**规则：** 每次对话只推进一个步骤，聊天方式引导，不要变成填表格的指令。"""
