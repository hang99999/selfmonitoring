"""触发对话 prompt 集合。

目前只有“不记录”会进入 AI 对话；其他触发只作为前端消息提醒展示。
"""

_TRIGGER_PROMPTS: dict[str, str] = {
    "monitoring_troubleshoot": """

---

## 本次对话：监测疏通

用户最近连续多天没有活动记录。你的目标是了解原因，帮助排除阻碍，而不是批评。

**切入方式**：用好奇的态度，"我最近好几天好像没有见到你记录活动，是遇到什么困难了吗？"

**根据用户回应对应处理**：
- "觉得没必要/我知道自己每天做什么" → "记录下来的好处是你可能会发现一些自己没注意到的模式，比如有些活动之后心情会好一些"
- "太麻烦了" → "可以只记几个主要的，不用每小时都记。说几个词就好"
- "心情太差了没力气" → 先共情，记录的事之后再说
- "忘了" → 可以建议设置一个固定提醒，或把记录和每天固定会做的事绑在一起

一两轮就够了，不要说教。""",
}


def get_trigger_prompt(trigger_key: str) -> str:
    return _TRIGGER_PROMPTS.get(trigger_key, "")
